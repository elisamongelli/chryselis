    ALTRO_DATO_SENSORI_3            DECIMAL(5,2),
    ALTRO_DATO_SENSORI_4            DECIMAL(5,2),

    CONSTRAINT PK_ACT_ANAGRAFICA_DETTAGLIO_SENSORI PRIMARY KEY (ID_PIANTA),
    CONSTRAINT FK_ACT_ANAGRAFICA_DETTAGLIO_SENSORI_PIANTA FOREIGN KEY (ID_PIANTA) REFERENCES ACT_ANAGRAFICA_PIANTE_TESTATA(ID_PIANTA)
);


